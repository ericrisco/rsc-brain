@router.post("/corrections/{correction_id}/revert")
async def revert_correction(
    correction_id: str, request: Request, scope: ProjectScope = Depends(_needs_knowledge_read)
) -> dict[str, object]:
    """Revert a correction (FR-15.8).

    The one mutation whose matrix row is not a pure role: the project administrator OR the owner of
    the target claim's topics may revert. That is expressed as
    :attr:`Capability.CORRECTION_REVERT` with the ownership fact passed in — the bespoke
    ``is_admin or is_owner`` gate this replaces was the reason T001 could not fold this route into
    the uniform matrix. A refusal is still audited.
    """
    from rsc_brain.knowledge.corrections import CorrectionService
    from rsc_brain.stores.age_graph_store import AgeGraphStore

    deps = _deps(request)
    sessionmaker = _sm(request)
    store = KnowledgeStore(sessionmaker)
    correction = await store.get_correction(scope, correction_id)
    if correction is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="correction not found")
    target = await store.get_claim(scope, str(correction.target_claim))
    if target is None:
        # The correction exists but its target claim is outside the caller's topic visibility:
        # reverting it would mutate knowledge the caller cannot see, and saying so would confirm
        # the claim exists. Absent and hidden look identical (FR-4.3, R06).
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="correction not found")
    tags = list(target.tags)
    is_owner = await store.person_owns_any_tag(scope, scope.principal_id, tags)
    decision = decide(
        scope, Capability.CORRECTION_REVERT, object_topics=tags, object_owner=is_owner
    )
    if not isinstance(decision, Allow):
        await audit_mod.record_audit(
            sessionmaker,
            scope,
            action="correct_knowledge:revert_denied",
            tool="console",
            denied=True,
        )
        enforce(decision)
    service = CorrectionService(
        store=store,
        graph=AgeGraphStore(sessionmaker),
        gateway=deps.gateway,  # type: ignore[attr-defined]
    )
    outcome = await service.revert(scope, correction_id)
    await audit_mod.record_audit(
        sessionmaker, scope, action=f"correct_knowledge:{outcome.status}", tool="console"
    )
    return {"status": outcome.status, "explanation": outcome.explanation}



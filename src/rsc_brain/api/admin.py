def _sm(request: Request) -> async_sessionmaker[AsyncSession]:
    sessionmaker: async_sessionmaker[AsyncSession] = _deps(request).sessionmaker  # type: ignore[attr-defined]
    return sessionmaker


async def _console_scope_for(
    sessionmaker: async_sessionmaker[AsyncSession], user_id: str, role: str, project_slug: str
) -> ProjectScope | None:
    """Scope a console-session user to a project they may act in (SPEC-14).

    ``role`` is the caller's PLATFORM role, and it is deliberately not consulted here: platform
    administration is not project content authority (AUDIT-020/R03), so every caller needs an
    explicit membership in this project — a project-admin of another project included (FR-12.5).
    The membership's own role and topics are what travel in the scope; a global role never widens
    them. ``None`` ⇒ denied ≡ absent (FR-4.3).
    """
    async with sessionmaker() as session:
        project_id = await session.scalar(
            select(models.Project.id).where(models.Project.slug == project_slug)
        )
        if project_id is None:
            return None
        membership = await session.scalar(
            select(models.ProjectMembership).where(
                models.ProjectMembership.user_id == uuid.UUID(user_id),
                models.ProjectMembership.project_id == project_id,
            )
        )
        if membership is None:
            return None
        return Principal(
            id=user_id,
            type=PrincipalType.HUMAN,
            allowed_topics=frozenset(membership.allowed_topics),
            can_curate=membership.can_curate,
            role=membership.role,
            platform_role=role,
        ).scope_for(str(project_id))


async def _identified_scope(
    request: Request, credentials: HTTPAuthorizationCredentials | None, project: str | None
) -> ProjectScope:
    """Resolve identity only — never authority — from either supported entry point.

    A project-scoped PAT/OAuth token carries its own project (FR-12.3); a console session must name
    the project it means with ``?project=<slug>`` and must be a member of it. Both produce the same
    :class:`ProjectScope`, so the capability decision that follows cannot depend on how the caller
    authenticated (the R04 defect: session and token were gated differently).
    """
    from rsc_brain.identity.resolve import resolve_scope
    from rsc_brain.identity.sessions import resolve_session

    sessionmaker = _sm(request)
    if credentials is None:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="missing bearer token")
    token = credentials.credentials
    scope = await resolve_scope(sessionmaker, token)
    if scope is not None:
        return scope
    user = await resolve_session(sessionmaker, token)
    if user is not None:
        scoped = (
            await _console_scope_for(sessionmaker, user.user_id, user.role, project)
            if project
            else None
        )
        if scoped is None:
            # No/unauthorized project → denied ≡ absent (never reveal another project exists).
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="not found")
        return scoped
    raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="invalid token")


def _requires(
    capability: Capability,
) -> Callable[..., Coroutine[Any, Any, ProjectScope]]:
    """A FastAPI dependency that resolves identity and decides ``capability`` before the route runs.

    Capabilities whose decision also depends on the *object* (a document's tags, a gap's topics)
    are decided a second time inside the route, once the object is known — the dependency is the
    floor, never the whole decision.
    """

    async def dependency(
        request: Request,
        credentials: HTTPAuthorizationCredentials | None = Depends(_bearer),
        project: str | None = None,
    ) -> ProjectScope:
        scope = await _identified_scope(request, credentials, project)
        enforce(decide(scope, capability))
        return scope

    return dependency


async def _needs_identity(
    request: Request,
    credentials: HTTPAuthorizationCredentials | None = Depends(_bearer),
    project: str | None = None,
) -> ProjectScope:
    """Resolve identity and decide nothing — for routes that act on ONE named object.

    Order matters for indistinguishability (FR-4.3): if the role were decided first, a caller of
    another project asking about this project's document would get the 403 shape while a caller
    asking about a genuinely nonexistent id got 404, which tells the first caller the document
    exists. So these routes look the object up in the caller's own project first (absent ⇒ 404) and
    only then decide the operation over its topics.
    """
    return await _identified_scope(request, credentials, project)



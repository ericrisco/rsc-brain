"""REST admin API (FR-10.2) — parity with the v0.1 CLI subset, capability-gated, OpenAPI-documented.

Every view need widens THIS API first (never direct DB): the console (SPEC-07) is built on the
autogenerated OpenAPI. Two entry points resolve to the same authority: a Bearer PAT/OAuth token
(project from the token, FR-12.3) or a console session plus the ``?project=`` slug it is authorized
for. Neither is trusted beyond identity — every route then names the *operation* it performs and
:func:`rsc_brain.authorization.decide` answers it against the ratified role matrix (AUDIT-020).

What that replaced (R03/R04): a single ``_is_admin`` helper that accepted ``can_curate`` as
administration, so a curator reached the whole surface while the project administrator the matrix
actually designates was locked out of it.
"""


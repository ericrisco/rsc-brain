    deps = _deps(request)
    chunk_topics = await object_topics(
        _sm(request), scope, models.Chunk, models.Chunk.id, chunk_id, topics_attr="tags"
    )
    if chunk_topics is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="not found")
    decide_object(
        scope,
        Capability.KNOWLEDGE_REVIEW_DECIDE,
        [*chunk_topics, *(body.tags or [])],
    )
    outcome = await resolve_chunk(
        deps.sessionmaker,  # type: ignore[attr-defined]
        scope,
        chunk_id,
        approve=approve,
        gateway=deps.gateway,  # type: ignore[attr-defined]
        tags=body.tags,
    )
    await audit_mod.record_audit(
        deps.sessionmaker,  # type: ignore[attr-defined]
        scope,
        action=f"review:chunk:{outcome}",
        tool="console",
    )
    return {"chunk_id": chunk_id, "outcome": outcome}



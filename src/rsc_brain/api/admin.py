@router.post("/documents/{document_id}/approve")
async def approve_document(
    document_id: str,
    body: ApproveDoc,
    request: Request,
    scope: ProjectScope = Depends(_needs_identity),
) -> dict[str, object]:
    """Approve a pending doc from the console (D13); corrected tags inherit to chunks (FR-1.15).

    R02: approving publishes every topic the document carries, and a corrected tag moves it into a
    new one, so the decision covers the union of the document's tags and the applied ones — a caller cannot publish into, or out of,
    a topic it does not hold. A document in another project is absent, never denied (FR-4.3).
    """
    from rsc_brain.ingest.pipeline import DocumentNotFoundError

    await decide_document(_sm(request), scope, document_id, extra_tags=body.tags)
    service, _ = _deps(request).service()  # type: ignore[attr-defined]
    try:
        run = await service.approve(scope, document_id, tags=body.tags, approver=scope.principal_id)
    except DocumentNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="not found") from exc
    return {"document_id": document_id, "phase": run.phase}


